"""Executor API schemas (pydantic) - shared by the sandbox layer, the service and the client.

Every value that crosses the Executor's HTTP boundary is one of these models, so the
OpenAPI document of the Executor service is the authoritative contract and the
:class:`~ono.executor.client.ExecutorClient` returns exactly these types.
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

SANDBOX_WORKSPACE = "/workspace"
"""Where the target code lives inside the jailed container (a bounded tmpfs)."""

SCAN_ID_PATTERN = r"^[a-z0-9][a-z0-9._-]{0,63}$"
"""Scan ids are server-generated by the harness (``scn_<hex>``); still validated here."""

SandboxStatus = Literal["running", "dead", "destroyed"]
"""``dead`` = the container stopped (OOM, fork bomb, ...); ``reset`` recreates it."""

TestRunner = Literal["pytest", "npm", "none"]


class SandboxInfo(BaseModel):
    """Metadata for one ephemeral sandbox (one per scan)."""

    sandbox_id: str = Field(examples=["sbx_7c1d2e3f4a5b"])
    scan_id: str
    status: SandboxStatus
    image: str
    container_id: str | None = Field(
        default=None, description="Docker container id (None if dead)."
    )
    created_at: datetime
    expires_at: datetime = Field(description="The TTL sweeper destroys the sandbox after this.")
    workspace: str = SANDBOX_WORKSPACE
    resets: int = Field(default=0, ge=0, description="How many times reset() recreated it.")


# ---------------------------------------------------------------------------
# Read-only operations
# ---------------------------------------------------------------------------


class ReadRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    path: str = Field(min_length=1, max_length=1024, description="Relative to the workspace.")
    start: int | None = Field(default=None, ge=1, description="First line (1-based, inclusive).")
    end: int | None = Field(default=None, ge=1, description="Last line (1-based, inclusive).")


class FileContent(BaseModel):
    path: str
    content: str
    start_line: int = Field(ge=1)
    end_line: int = Field(ge=0, description="0 when the slice is empty.")
    total_lines: int | None = Field(default=None, description="None if the file was truncated.")
    size_bytes: int = Field(ge=0)
    truncated: bool = False


class TreeRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    path: str = Field(default=".", max_length=1024)
    max_entries: int = Field(default=2000, ge=1, le=20_000)
    max_depth: int = Field(default=12, ge=1, le=64)


class TreeEntry(BaseModel):
    path: str
    kind: Literal["file", "dir", "symlink", "other"]
    size: int = Field(ge=0)


class TreeListing(BaseModel):
    entries: list[TreeEntry]
    truncated: bool = False
    total: int = Field(ge=0, description="Entries returned (<= max_entries).")


class GrepRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    pattern: str = Field(min_length=1, max_length=512, description="Python ``re`` syntax.")
    path: str = Field(default=".", max_length=1024, description="File or directory to search.")
    ignore_case: bool = False
    max_matches: int = Field(default=200, ge=1, le=5000)


class GrepMatch(BaseModel):
    file: str
    line: int = Field(ge=1)
    text: str


class GrepResult(BaseModel):
    matches: list[GrepMatch]
    truncated: bool = False
    files_scanned: int = Field(ge=0)


# ---------------------------------------------------------------------------
# Mutating operations
# ---------------------------------------------------------------------------


class PatchRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    diff: str = Field(min_length=1, max_length=2_000_000, description="Unified diff.")


class PatchResult(BaseModel):
    applied: bool
    reason: str = Field(default="", description="Why the patch was rejected (empty on success).")
    files: list[str] = Field(default_factory=list, description="Workspace paths that changed.")


class RunRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    cmd: str = Field(min_length=1, max_length=20_000, description="Run with ``sh -c`` in the jail.")
    timeout_s: float | None = Field(
        default=None,
        gt=0,
        description="Hard timeout; capped at the server's sandbox_cmd_timeout_s.",
    )


class RunResult(BaseModel):
    cmd: str
    stdout: str
    stderr: str
    exit_code: int | None = Field(description="None only if the exit status could not be read.")
    duration_ms: float = Field(ge=0)
    timed_out: bool = False
    oom_killed: bool = False
    truncated: bool = Field(default=False, description="Output exceeded the byte cap and was cut.")


class TestRunRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    timeout_s: float | None = Field(default=None, gt=0)


class TestRunResult(BaseModel):
    runner: TestRunner
    command: str = ""
    detected: bool
    passed: bool | None = Field(
        description="None if nothing ran / nothing was collected / timeout."
    )
    summary: str = ""
    run: RunResult | None = None


class ExecutorHealth(BaseModel):
    status: Literal["ok", "degraded"] = "ok"
    docker: bool = Field(description="Whether the Docker daemon answered a ping.")
    active_sandboxes: int = Field(ge=0)
